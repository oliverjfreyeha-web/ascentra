/** A slot a learner can see: its module's course is live and open to them, and the lesson that shows it is published. */
async function learnerSlot(actor: Account, slotId: string) {
  if (!isUuid(slotId)) return null;
  const db = getDb();
  const slot = (await db.from("video_slots").select("*").eq("id", slotId).maybeSingle()).data as Slot | null;
  if (!slot) return null;
  const mod = (await db.from("modules").select("id, course_id").eq("id", slot.module_id).maybeSingle()).data as { id: string; course_id: string } | null;
  const course = mod ? ((await db.from("courses").select("id, academy_id, status, unpublished_at").eq("id", mod.course_id).maybeSingle()).data as { id: string; academy_id: string; status: string; unpublished_at: string | null } | null) : null;
  if (!mod || !course || (course.status !== "published" && course.status !== "restored")) return null;
  const academy = (await db.from("academies").select("id, slug").eq("id", course.academy_id).maybeSingle()).data as { id: string; slug: string } | null;
  if (!academy || !(await canOpenCourse(actor, academy, !!course.unpublished_at))) return null;
  const lessons = ((await db.from("lessons").select("id").eq("module_id", mod.id)).data ?? []) as { id: string }[];
  const published = ((await db.from("lesson_versions").select("lesson_id").in("lesson_id", lessons.length ? lessons.map((l) => l.id) : [slot.id]).eq("status", "published")).data ?? []) as { lesson_id: string }[];
  const seen = slot.lesson_id ? published.some((p) => p.lesson_id === slot.lesson_id) : published.length > 0;
  return seen ? slot : null;
}

/** The video slots a lesson shows: its own, and the module's general ones on the module's first lesson. */
export async function lessonVideos(lessonId: string) {
  const db = getDb();
  const lesson = (await db.from("lessons").select("id, module_id, position").eq("id", lessonId).maybeSingle()).data as { id: string; module_id: string; position: number } | null;
  if (!lesson) return [];
  const first = (((await db.from("lessons").select("id, position").eq("module_id", lesson.module_id)).data ?? []) as { id: string; position: number }[]).sort((a, b) => a.position - b.position)[0];
  const slots = (((await db.from("video_slots").select("id, lesson_id, position, title, status, transcript").eq("module_id", lesson.module_id)).data ?? []) as
    { id: string; lesson_id: string | null; position: number; title: string; status: string; transcript: string | null }[])
    .filter((s) => s.lesson_id === lessonId || (!s.lesson_id && first?.id === lessonId)).sort((a, b) => a.position - b.position);
  // Never a fake player: an approved video, or plain "Video coming".
  return slots.map((s) => s.status === "approved"
    ? { id: s.id, title: s.title, state: "ready" as const, transcript: s.transcript ?? "" }
    : { id: s.id, title: s.title, state: "coming" as const, transcript: null });
}

/** A learner's link to an approved video: ten minutes, and only when they may see the lesson it belongs to. */
export async function learnerVideoLink(actor: Account, slotId: string): Promise<Result> {
  const A2 = "learn.video";
  const slot = await learnerSlot(actor, slotId);
  if (!slot) return refused(404, "No such video.", A2);
  if (slot.status !== "approved" || !slot.current_upload_id) return refused(404, "Video coming: this video isn't ready yet.", A2);
  const up = (await getDb().from("video_uploads").select("storage_path, mime").eq("id", slot.current_upload_id).maybeSingle()).data as { storage_path: string; mime: string } | null;
  const url = up ? await signDownload(up.storage_path, VIDEO_LINK_SECONDS) : null;
  if (!url) return refused(503, "The video can't be played right now. Its transcript is below.", A2);
  return { ok: true, body: { id: slot.id, title: slot.title, url, mime: up!.mime, expiresIn: VIDEO_LINK_SECONDS, transcript: slot.transcript ?? "" }, event: { action: A2, result: "Completed", context: "" } };
}
